/**
 * Get a letter grid by character (case-insensitive)
 */
export function getLetter(char: string): LetterGrid | undefined {
  return alphabet[char.toUpperCase()];
}

/**
 * Get all available letters
 */
export function getAvailableLetters(): string[] {
  return Object.keys(alphabet);
}
